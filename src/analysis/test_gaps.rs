use super::symbols::{Symbol, SymbolAnalysis};
use std::collections::{BTreeSet, HashMap};
use std::fs;
use std::path::Path;
use tree_sitter::{Node, Parser};

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TestGap {
    pub symbol: Symbol,
    pub explanation: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TestGapDiagnostic {
    pub file: String,
    pub message: String,
}

#[derive(Debug, Default)]
pub struct TestGapAnalysis {
    pub gaps: Vec<TestGap>,
    pub diagnostics: Vec<TestGapDiagnostic>,
}

pub fn analyze_test_gaps(
    source_files: &[String],
    repository_root: &Path,
    symbol_analysis: &SymbolAnalysis,
) -> TestGapAnalysis {
    let mut sources = Vec::new();
    let mut diagnostics = Vec::new();

    for file in source_files {
        if !file.ends_with(".rs") {
            continue;
        }

        match fs::read_to_string(repository_root.join(file)) {
            Ok(source) => sources.push((file.clone(), source)),
            Err(error) => diagnostics.push(TestGapDiagnostic {
                file: file.clone(),
                message: format!("Failed to read source file: {error}"),
            }),
        }
    }

    let mut analysis = analyze_test_gaps_from_sources(&sources, symbol_analysis);
    analysis.diagnostics.extend(diagnostics);
    analysis
}

fn analyze_test_gaps_from_sources(
    sources: &[(String, String)],
    symbol_analysis: &SymbolAnalysis,
) -> TestGapAnalysis {
    let mut analysis = TestGapAnalysis::default();
    let mut tested_function_names = BTreeSet::new();
    let mut tested_method_names = BTreeSet::new();

    for (file, source) in sources {
        if !file.ends_with(".rs") {
            continue;
        }

        let mut parser = Parser::new();

        if let Err(error) = parser.set_language(&tree_sitter_rust::LANGUAGE.into()) {
            analysis.diagnostics.push(TestGapDiagnostic {
                file: file.clone(),
                message: format!("Could not load Rust grammar: {error}"),
            });
            continue;
        }

        let Some(tree) = parser.parse(source, None) else {
            analysis.diagnostics.push(TestGapDiagnostic {
                file: file.clone(),
                message: "Tree-sitter could not parse this source file.".to_string(),
            });
            continue;
        };

        if tree.root_node().has_error() {
            analysis.diagnostics.push(TestGapDiagnostic {
                file: file.clone(),
                message: "Syntax errors found; test calls in this file were skipped.".to_string(),
            });
            continue;
        }

        collect_test_calls(
            tree.root_node(),
            source,
            &mut tested_function_names,
            &mut tested_method_names,
        );
    }

    let mut free_function_counts: HashMap<String, usize> = HashMap::new();
    let mut method_counts: HashMap<String, usize> = HashMap::new();

    for symbol in &symbol_analysis.symbols {
        if !is_production_target(symbol) {
            continue;
        }

        let counts = if is_associated_method(symbol) {
            &mut method_counts
        } else {
            &mut free_function_counts
        };

        *counts.entry(symbol.name.clone()).or_default() += 1;
    }

    for symbol in &symbol_analysis.symbols {
        if !is_production_target(symbol) {
            continue;
        }

        let (counts, tested_names) = if is_associated_method(symbol) {
            (&method_counts, &tested_method_names)
        } else {
            (&free_function_counts, &tested_function_names)
        };

        if counts.get(&symbol.name) != Some(&1) {
            continue;
        }

        if !tested_names.contains(&symbol.name) {
            analysis.gaps.push(TestGap {
                symbol: symbol.clone(),
                explanation: format!(
                    "No direct call to '{}' was detected inside recognized test functions. \
                     This does not rule out indirect coverage or tests generated by \
                     macros or unsupported test frameworks.",
                    symbol.name
                ),
            });
        }
    }

    analysis.gaps.sort_by(|left, right| {
        left.symbol
            .file
            .cmp(&right.symbol.file)
            .then(left.symbol.start_line.cmp(&right.symbol.start_line))
            .then(left.symbol.name.cmp(&right.symbol.name))
    });

    analysis
}

fn is_production_target(symbol: &Symbol) -> bool {
    symbol.kind == "function"
        && !symbol.is_test
        && matches!(
            symbol.visibility.as_deref(),
            Some("pub") | Some("pub(crate)")
        )
}

fn is_associated_method(symbol: &Symbol) -> bool {
    symbol.scope.iter().any(|scope| scope.starts_with("impl "))
}

// Rust attributes are sibling nodes immediately before their declarations.
// Keep consecutive attributes and associate them with the next function item.
fn collect_test_calls(
    node: Node,
    source: &str,
    function_calls: &mut BTreeSet<String>,
    method_calls: &mut BTreeSet<String>,
) {
    let mut cursor = node.walk();
    let children: Vec<Node> = node.named_children(&mut cursor).collect();
    let mut pending_attributes = Vec::new();

    for child in children {
        if child.kind() == "attribute_item" {
            pending_attributes.push(child);
            continue;
        }

        if child.kind() == "function_item" {
            if is_test_function(&pending_attributes, source) {
                if let Some(body) = child.child_by_field_name("body") {
                    collect_call_expressions(body, source, function_calls, method_calls);
                }
            } else {
                collect_test_calls(child, source, function_calls, method_calls);
            }

            pending_attributes.clear();
            continue;
        }

        pending_attributes.clear();
        collect_test_calls(child, source, function_calls, method_calls);
    }
}

fn is_test_function(attributes: &[Node], source: &str) -> bool {
    for attribute_node in attributes {
        let Ok(attribute) = attribute_node.utf8_text(source.as_bytes()) else {
            continue;
        };

        let attribute = attribute.trim();

        if attribute.contains("cfg(test)") {
            continue;
        }

        let path = attribute
            .strip_prefix("#[")
            .and_then(|value| value.strip_suffix(']'))
            .unwrap_or(attribute)
            .split('(')
            .next()
            .unwrap_or("")
            .trim();

        if path == "test" || path.ends_with("::test") {
            return true;
        }
    }

    false
}

fn collect_call_expressions(
    node: Node,
    source: &str,
    function_calls: &mut BTreeSet<String>,
    method_calls: &mut BTreeSet<String>,
) {
    if node.kind() == "call_expression" {
        if let Some(function) = node.child_by_field_name("function") {
            if function.kind() == "field_expression" {
                if let Some(field) = function.child_by_field_name("field") {
                    if let Some(name) = terminal_name(field, source) {
                        method_calls.insert(name);
                    }
                }
            } else if let Some(name) = terminal_name(function, source) {
                function_calls.insert(name);
            }
        }
    }

    let mut cursor = node.walk();

    for child in node.named_children(&mut cursor) {
        collect_call_expressions(child, source, function_calls, method_calls);
    }
}

fn terminal_name(node: Node, source: &str) -> Option<String> {
    match node.kind() {
        "identifier" | "field_identifier" => {
            node.utf8_text(source.as_bytes()).ok().map(str::to_string)
        }
        "field_expression" => None,
        "scoped_identifier" => node
            .child_by_field_name("name")
            .and_then(|child| terminal_name(child, source)),
        "generic_function" => node
            .child_by_field_name("function")
            .and_then(|child| terminal_name(child, source)),
        _ => {
            let mut cursor = node.walk();
            let children: Vec<Node> = node.named_children(&mut cursor).collect();

            children
                .last()
                .and_then(|child| terminal_name(*child, source))
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::analysis::symbols::analyze_rust_file;

    fn build_symbols(sources: &[(&str, &str)]) -> SymbolAnalysis {
        let mut symbols = Vec::new();

        for (file, source) in sources {
            symbols.extend(
                analyze_rust_file(source, file)
                    .unwrap_or_else(|error| panic!("Symbol analysis failed: {error}")),
            );
        }

        SymbolAnalysis {
            symbols,
            diagnostics: Vec::new(),
        }
    }

    fn run_analysis(
        production_sources: &[(&str, &str)],
        test_sources: &[(&str, &str)],
    ) -> TestGapAnalysis {
        let symbol_analysis = build_symbols(production_sources);

        let sources: Vec<(String, String)> = production_sources
            .iter()
            .chain(test_sources.iter())
            .map(|(file, source)| (file.to_string(), source.to_string()))
            .collect();

        analyze_test_gaps_from_sources(&sources, &symbol_analysis)
    }

    #[test]
    fn reports_public_function_without_direct_test_call() {
        let analysis = run_analysis(
            &[("src/lib.rs", "pub fn create_user() {}")],
            &[(
                "tests/basic.rs",
                "#[test] fn unrelated_test() { assert_eq!(1, 1); }",
            )],
        );

        assert_eq!(analysis.gaps.len(), 1);
        assert_eq!(analysis.gaps[0].symbol.name, "create_user");
    }

    #[test]
    fn recognizes_direct_call_from_test() {
        let analysis = run_analysis(
            &[("src/lib.rs", "pub fn create_user() {}")],
            &[(
                "tests/basic.rs",
                "#[test] fn create_user_test() { crate::create_user(); }",
            )],
        );

        assert!(analysis.gaps.is_empty());
    }

    #[test]
    fn recognizes_async_test_attributes() {
        let analysis = run_analysis(
            &[("src/lib.rs", "pub async fn fetch_data() {}")],
            &[(
                "tests/async_tests.rs",
                "#[tokio::test] async fn fetch_test() { fetch_data().await; }",
            )],
        );

        assert!(analysis.gaps.is_empty());
    }

    #[test]
    fn ignores_comments_and_string_literals() {
        let analysis = run_analysis(
            &[("src/lib.rs", "pub fn create_user() {}")],
            &[(
                "tests/basic.rs",
                r#"
                #[test]
                fn unrelated_test() {
                    // create_user();
                    let example = "create_user()";
                    assert!(!example.is_empty());
                }
                "#,
            )],
        );

        assert_eq!(analysis.gaps.len(), 1);
        assert_eq!(analysis.gaps[0].symbol.name, "create_user");
    }

    #[test]
    fn excludes_private_functions() {
        let analysis = run_analysis(&[("src/lib.rs", "fn internal_helper() {}")], &[]);

        assert!(analysis.gaps.is_empty());
    }

    #[test]
    fn excludes_test_symbols_from_production_targets() {
        let mut symbol_analysis = build_symbols(&[("src/lib.rs", "pub fn public_api() {}")]);

        let mut test_symbol =
            analyze_rust_file("pub fn test_helper() {}", "tests/helpers.rs").unwrap();

        test_symbol[0].is_test = true;
        symbol_analysis.symbols.extend(test_symbol);

        let sources = vec![
            (
                "src/lib.rs".to_string(),
                "pub fn public_api() {}".to_string(),
            ),
            (
                "tests/helpers.rs".to_string(),
                "pub fn test_helper() {}".to_string(),
            ),
        ];

        let analysis = analyze_test_gaps_from_sources(&sources, &symbol_analysis);

        assert_eq!(analysis.gaps.len(), 1);
        assert_eq!(analysis.gaps[0].symbol.name, "public_api");
    }

    #[test]
    fn skips_ambiguous_same_name_targets() {
        let analysis = run_analysis(
            &[
                ("src/first.rs", "pub fn process() {}"),
                ("src/second.rs", "pub fn process() {}"),
            ],
            &[],
        );

        assert!(analysis.gaps.is_empty());
    }

    #[test]
    fn recognizes_direct_call_to_associated_method() {
        let analysis = run_analysis(
            &[(
                "src/lib.rs",
                "pub struct Finding; impl Finding { pub fn validate(&self) {} }",
            )],
            &[(
                "tests/basic.rs",
                "#[test] fn validates_finding() { let finding = Finding; finding.validate(); }",
            )],
        );

        assert!(analysis.gaps.is_empty());
    }

    #[test]
    fn method_call_does_not_count_as_free_function_coverage() {
        let analysis = run_analysis(
            &[("src/lib.rs", "pub fn save() {}")],
            &[(
                "tests/basic.rs",
                r#"
                #[test]
                fn service_test() {
                    let service = Service;
                    service.save();
                }
                "#,
            )],
        );

        assert_eq!(analysis.gaps.len(), 1);
        assert_eq!(analysis.gaps[0].symbol.name, "save");
    }

    #[test]
    fn reports_parse_errors_as_diagnostics() {
        let analysis = run_analysis(
            &[("src/lib.rs", "pub fn create_user() {}")],
            &[("tests/broken.rs", "#[test] fn broken( {")],
        );

        assert_eq!(analysis.gaps.len(), 1);
        assert!(!analysis.diagnostics.is_empty());
        assert!(analysis.diagnostics[0].message.contains("Syntax errors"));
    }
}
